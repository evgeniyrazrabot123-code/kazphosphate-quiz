def seed_questions():
    db = SessionLocal()

    try:
        print("Очистка старых вопросов...")
        db.query(Question).delete()
        db.commit()

        total_questions = 0

        for cat_code, role_ru, role_kk in CATEGORIES:
            for idx, (tmpl_ru, tmpl_kk, options_ru, correct_idx) in enumerate(QUESTION_TEMPLATES, 1):
                text_ru = tmpl_ru.format(role=role_ru)
                text_kk = tmpl_kk.format(role_kk=role_kk)
                
                # Казахские варианты ответов
                options_kk = [
                    "Техникалық жағдайды және қауіпсіздік құралдарын тексеру" if i == 0 else "Тексерусіз бірден жұмысты бастау" if i == 1 else "Тек жанармай деңгейін тексеру"
                    for i in range(len(options_ru))
                ]

                q = Question(
                    category=cat_code,
                    text_ru=f"[{idx}/20] {text_ru}",
                    text_kk=f"[{idx}/20] {text_kk}",
                    options_ru=json.dumps(options_ru, ensure_ascii=False),
                    options_kk=json.dumps(options_kk, ensure_ascii=False),
                    correct_option_index=correct_idx
                )
                db.add(q)
                total_questions += 1

        db.commit()
        print(f"✅ УСПЕШНО! База данных заполнена: {len(CATEGORIES)} специальностей x 20 вопросов = {total_questions} вопросов всего.")
    except Exception as e:
        db.rollback()
        print(f"❌ Ошибка заполнения базы данных: {e}")
    finally:
        db.close()

if __name__ == "__main__":
    seed_questions()